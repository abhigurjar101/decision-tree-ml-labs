from pathlib import Path
"""
=============================================================================
DECISION TREE CLASSIFICATION MASTER LAB
End-to-End Practical Implementation with Scikit-Learn
Case Study: Bank Loan Approval Prediction
=============================================================================
This script demonstrates:
1. Data loading & Exploratory Data Analysis (EDA)
2. Stratified train/test splitting
3. Training DecisionTreeClassifier (Gini vs Entropy)
4. Model evaluation: Confusion Matrix, Classification Report, ROC-AUC
5. Tree visualization (Text-based & Matplotlib plot)
6. Feature Importance extraction & interpretation
7. Hyperparameter tuning using GridSearchCV
8. Stratified K-Fold Cross-Validation
9. Cost-Complexity Pruning (ccp_alpha)
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.tree import DecisionTreeClassifier, export_text, plot_tree
from sklearn.model_selection import train_test_split, GridSearchCV, StratifiedKFold, cross_val_score
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score, f1_score,
    confusion_matrix, classification_report, roc_auc_score, roc_curve
)

def run_classification_pipeline():
    print("=" * 70)
    print("STEP 1: LOAD & EXPLORE DATA")
    print("=" * 70)
    # Load dataset generated by generate_assets.py
    df = pd.read_csv(Path(__file__).resolve().parent / "data" / "bank_loan_data.csv")
    print("Dataset Shape:", df.shape)
    print("\nFirst 5 Rows:")
    print(df.head())
    print("\nClass Distribution:")
    print(df['Approved'].value_counts(normalize=True).round(3))

    feature_cols = ['Income ($)', 'Credit_Score', 'Existing_Debt ($)', 'Loan_Amount ($)']
    X = df[feature_cols]
    y = df['Approved']

    print("\n" + "=" * 70)
    print("STEP 2: STRATIFIED TRAIN / TEST SPLIT")
    print("=" * 70)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, random_state=42, stratify=y
    )
    print(f"Training set: {X_train.shape[0]} samples")
    print(f"Testing set:  {X_test.shape[0]} samples")

    print("\n" + "=" * 70)
    print("STEP 3: TRAIN BASELINE DECISION TREE CLASSIFIER")
    print("=" * 70)
    # Training with max_depth=3 for interpretability
    clf = DecisionTreeClassifier(criterion='gini', max_depth=3, random_state=42)
    clf.fit(X_train, y_train)

    print("\n" + "=" * 70)
    print("STEP 4: MODEL EVALUATION & METRICS")
    print("=" * 70)
    y_pred = clf.predict(X_test)
    y_prob = clf.predict_proba(X_test)[:, 1]

    acc = accuracy_score(y_test, y_pred)
    prec = precision_score(y_test, y_pred)
    rec = recall_score(y_test, y_pred)
    f1 = f1_score(y_test, y_pred)
    auc = roc_auc_score(y_test, y_prob)

    print(f"Accuracy:  {acc:.4f}")
    print(f"Precision: {prec:.4f}")
    print(f"Recall:    {rec:.4f}")
    print(f"F1-Score:  {f1:.4f}")
    print(f"ROC-AUC:   {auc:.4f}")

    print("\nConfusion Matrix:")
    cm = confusion_matrix(y_test, y_pred)
    print(cm)
    print(f"  [TN={cm[0,0]}  FP={cm[0,1]}]")
    print(f"  [FN={cm[1,0]}  TP={cm[1,1]}]")

    print("\nClassification Report:")
    print(classification_report(y_test, y_pred, target_names=['Denied (0)', 'Approved (1)']))

    print("\n" + "=" * 70)
    print("STEP 5: TREE RULES IN PLAIN TEXT")
    print("=" * 70)
    rules = export_text(clf, feature_names=feature_cols)
    print(rules)

    print("\n" + "=" * 70)
    print("STEP 6: FEATURE IMPORTANCES (GINI IMPORTANCE / MDI)")
    print("=" * 70)
    importances = pd.DataFrame({
        'Feature': feature_cols,
        'Importance': clf.feature_importances_
    }).sort_values('Importance', ascending=False)
    print(importances.to_string(index=False))

    print("\n" + "=" * 70)
    print("STEP 7: 5-FOLD STRATIFIED CROSS-VALIDATION")
    print("=" * 70)
    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
    cv_scores = cross_val_score(clf, X_train, y_train, cv=skf, scoring='accuracy')
    print(f"5-Fold CV Accuracy: {cv_scores.mean():.4f} +/- {cv_scores.std():.4f}")
    print("Fold Scores:", np.round(cv_scores, 4))

    print("\n" + "=" * 70)
    print("STEP 8: HYPERPARAMETER TUNING VIA GRIDSEARCHCV")
    print("=" * 70)
    param_grid = {
        'criterion': ['gini', 'entropy'],
        'max_depth': [2, 3, 4, 5, 6, 8, None],
        'min_samples_split': [2, 5, 10, 20],
        'min_samples_leaf': [1, 2, 5, 10]
    }
    grid = GridSearchCV(
        DecisionTreeClassifier(random_state=42),
        param_grid,
        cv=skf,
        scoring='roc_auc',
        n_jobs=1
    )
    grid.fit(X_train, y_train)

    print("Best Hyperparameters Found:")
    for k, v in grid.best_params_.items():
        print(f"  {k}: {v}")
    print(f"Best CV ROC-AUC: {grid.best_score_:.4f}")

    best_model = grid.best_estimator_
    best_test_auc = roc_auc_score(y_test, best_model.predict_proba(X_test)[:, 1])
    print(f"Tuned Model Test ROC-AUC: {best_test_auc:.4f}")

    print("\n" + "=" * 70)
    print("STEP 9: COST-COMPLEXITY PRUNING (ccp_alpha)")
    print("=" * 70)
    full_tree = DecisionTreeClassifier(random_state=42)
    path = full_tree.cost_complexity_pruning_path(X_train, y_train)
    print(f"Computed {len(path.ccp_alphas)} candidate alpha thresholds.")
    print(f"Smallest alpha: {path.ccp_alphas[0]:.6f} (Deepest Tree)")
    print(f"Largest alpha:  {path.ccp_alphas[-1]:.6f} (Root Node Only)")

    print("\nEducational pipeline complete; this is not a production lending model.")

if __name__ == "__main__":
    run_classification_pipeline()
